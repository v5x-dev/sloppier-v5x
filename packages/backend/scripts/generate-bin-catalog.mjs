// Turns data/bin/vex-v5rc-legal-parts.csv into convex/binCatalogData.ts.
// Run with: node scripts/generate-bin-catalog.mjs
import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const csvPath = join(root, "data/bin/vex-v5rc-legal-parts.csv")
const outPath = join(root, "convex/binCatalogData.ts")

// Minimal RFC 4180 parser: quoted fields may hold commas and doubled quotes.
function parseCsv(text) {
  const rows = []
  let row = []
  let field = ""
  let quoted = false
  for (let i = 0; i < text.length; i++) {
    const ch = text[i]
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        field += '"'
        i++
      } else if (ch === '"') {
        quoted = false
      } else {
        field += ch
      }
    } else if (ch === '"') {
      quoted = true
    } else if (ch === ",") {
      row.push(field)
      field = ""
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++
      row.push(field)
      field = ""
      if (row.some((cell) => cell !== "")) rows.push(row)
      row = []
    } else {
      field += ch
    }
  }
  if (field !== "" || row.length > 0) {
    row.push(field)
    rows.push(row)
  }
  return rows
}

const [header, ...body] = parseCsv(readFileSync(csvPath, "utf8"))
const col = Object.fromEntries(header.map((name, i) => [name, i]))
const required = ["sku", "name", "part_type", "alternate_skus", "retrieved_at"]
for (const name of required) {
  if (!(name in col)) throw new Error(`CSV is missing column ${name}`)
}

const rows = body.map((cells) => ({
  sku: cells[col.sku],
  name: cells[col.name],
  partType: cells[col.part_type],
  alternateSkus: cells[col.alternate_skus]
    ? cells[col.alternate_skus]
        .split(";")
        .map((s) => s.trim())
        .filter(Boolean)
    : [],
  retrievedAt: cells[col.retrieved_at],
}))

// The VEX C-channels are eight rows, one per material, width, and length the
// catalog sells. They become one part, C-Channel, whose options (material,
// width, length) are chosen in the app. The VEX numbers stay as alternate SKUs.
// Keep the name pattern in step with variantForVexName in
// convex/lib/binCChannel.ts.
const C_CHANNEL_SKU = "C-CHANNEL"
const vexCChannel = /^1x\d+x1x\d+ (Steel|Aluminum) C-Channel$/
const entries = []
for (const row of rows) {
  if (!vexCChannel.test(row.name)) {
    entries.push(row)
    continue
  }
  let family = entries.find((entry) => entry.sku === C_CHANNEL_SKU)
  if (!family) {
    family = {
      sku: C_CHANNEL_SKU,
      name: "C-Channel",
      partType: row.partType,
      alternateSkus: [],
      retrievedAt: row.retrievedAt,
    }
    entries.push(family)
  }
  family.alternateSkus.push(row.sku)
}

const source = `// Generated by scripts/generate-bin-catalog.mjs from data/bin/vex-v5rc-legal-parts.csv.
// Do not edit by hand.
export const binCatalogRows = ${JSON.stringify(entries, null, 2)} as const
`
writeFileSync(outPath, source)
// Keep the output in the repo's Prettier style so `bun run format:check` stays clean.
execFileSync(
  join(root, "../../node_modules/.bin/prettier"),
  ["--write", outPath],
  { stdio: "ignore" }
)
console.log(`wrote ${entries.length} catalog rows to convex/binCatalogData.ts`)
