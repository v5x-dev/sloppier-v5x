export function pierreFileIcon(path: string): ImageSourcePropType {
  const name = (path.split("/").pop() ?? path).toLowerCase()
  let icon = FILE_ICON_BY_NAME[name]
  if (!icon && name.startsWith("tsconfig.") && name.endsWith(".json"))
    icon = "typescript"
  const parts = name.split(".")
  for (let index = 1; !icon && index < parts.length; index++)
    icon = FILE_ICON_BY_EXTENSION[parts.slice(index).join(".")]
  return sources[icon ?? "default"]
}
